package ru.self.printlab_backend.stl;

/** Stable API codes and actionable messages; parser diagnostics stay in server logs. */
public enum StlUploadError {
    INVALID_STL("Не удалось открыть модель: файл повреждён или сохранён в неподдерживаемом формате. Экспортируйте модель в STL заново и загрузите её."),
    DEGENERATE_FACE("В модели есть повреждённая грань: её вершины совпадают или лежат на одной линии. Исправьте модель в 3D-редакторе и экспортируйте STL заново."),
    INVALID_COORDINATES("Не удалось определить размеры модели: в файле некорректно записана её форма. Проверьте масштаб модели и экспортируйте STL заново."),
    EMPTY_MODEL("В файле нет поверхности модели. Выберите другой STL-файл или экспортируйте модель заново."),
    TOO_MANY_TRIANGLES("Модель слишком подробная: больше 100 000 граней. Уменьшите детализацию при экспорте и загрузите STL заново."),
    FILE_TOO_LARGE("Файл больше 15 МБ. Уменьшите детализацию при экспорте или выберите файл меньшего размера."),
    EMPTY_FILE("Выбранный файл пуст. Выберите другой STL-файл или экспортируйте модель заново."),
    WRONG_FILE_TYPE("Этот формат не поддерживается. Выберите файл с расширением .stl."),
    INVALID_FILE_NAME("Не удалось загрузить файл с таким именем. Задайте короткое имя, не больше 255 символов, и попробуйте ещё раз.");

    private final String message;

    StlUploadError(String message) { this.message = message; }

    public String message() { return message; }
}
